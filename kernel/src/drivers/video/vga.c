/**
 * VESA Graphics Mode Driver (1920x1080 24-bit color)
 * 
 * Provides graphics output capabilities for the Nafuraito kernel.
 * The video mode is set by the bootloader via VESA BIOS calls.
 * Framebuffer info is passed from bootloader to kernel.
 */

#include "../stdint.h"

/*=============================================================================
 * Constants and Definitions
 *===========================================================================*/

#define VGA_GFX_WIDTH   1920
#define VGA_GFX_HEIGHT  1080
#define VGA_GFX_BPP     3  /* 24-bit = 3 bytes per pixel */
#define VGA_GFX_PITCH   (VGA_GFX_WIDTH * VGA_GFX_BPP)

/* Default framebuffer address - will be overwritten by bootloader info */
#define VGA_GFX_MEMORY  0xFD000000

/*=============================================================================
 * Static Variables
 *===========================================================================*/

static volatile uint8_t* gfx_buffer = (volatile uint8_t*)VGA_GFX_MEMORY;
static uint32_t gfx_pitch = VGA_GFX_PITCH;
static uint32_t gfx_width = VGA_GFX_WIDTH;
static uint32_t gfx_height = VGA_GFX_HEIGHT;
static uint32_t gfx_bpp = VGA_GFX_BPP;

/*=============================================================================
 * Color Manipulation
 *===========================================================================*/

typedef struct {
	uint8_t b;
	uint8_t g;
	uint8_t r;
} __attribute__((packed)) rgb24_t;

static inline rgb24_t make_rgb(uint8_t r, uint8_t g, uint8_t b)
{
	rgb24_t color = { b, g, r };
	return color;
}

static inline uint32_t rgb_to_u32(uint8_t r, uint8_t g, uint8_t b)
{
	return ((uint32_t)r << 16) | ((uint32_t)g << 8) | b;
}

/*=============================================================================
 * Internal Graphics Functions
 *===========================================================================*/

static void gfx_clear_screen(uint8_t r, uint8_t g, uint8_t b)
{
	uint32_t y, x;
	for (y = 0; y < gfx_height; y++) {
		volatile uint8_t* row = gfx_buffer + y * gfx_pitch;
		for (x = 0; x < gfx_width; x++) {
			row[x * gfx_bpp + 0] = b;
			row[x * gfx_bpp + 1] = g;
			row[x * gfx_bpp + 2] = r;
			if (gfx_bpp == 4) row[x * gfx_bpp + 3] = 0xFF; /* Alpha */
		}
	}
}

static void gfx_initialize(void)
{
	/* Mode should already be set by bootloader */
	gfx_clear_screen(0, 0, 0);
}

static void gfx_put_pixel(uint16_t x, uint16_t y, uint8_t r, uint8_t g, uint8_t b)
{
	if (x < gfx_width && y < gfx_height) {
		volatile uint8_t* pixel = gfx_buffer + y * gfx_pitch + x * gfx_bpp;
		pixel[0] = b;
		pixel[1] = g;
		pixel[2] = r;
		if (gfx_bpp == 4) pixel[3] = 0xFF; /* Alpha */
	}
}

static void gfx_draw_rect(uint16_t x, uint16_t y, uint16_t width, uint16_t height,
						  uint8_t r, uint8_t g, uint8_t b)
{
	uint16_t i, j;
	uint16_t x_end = (x + width > gfx_width) ? gfx_width : x + width;
	uint16_t y_end = (y + height > gfx_height) ? gfx_height : y + height;

	for (j = y; j < y_end; j++) {
		volatile uint8_t* row = gfx_buffer + j * gfx_pitch;
		for (i = x; i < x_end; i++) {
			row[i * gfx_bpp + 0] = b;
			row[i * gfx_bpp + 1] = g;
			row[i * gfx_bpp + 2] = r;
			if (gfx_bpp == 4) row[i * gfx_bpp + 3] = 0xFF;
		}
	}
}

static inline int16_t abs_i16(int16_t val)
{
	return (val < 0) ? -val : val;
}

static void gfx_draw_line(int16_t x0, int16_t y0, int16_t x1, int16_t y1,
						  uint8_t r, uint8_t g, uint8_t b)
{
	int16_t dx = abs_i16(x1 - x0);
	int16_t dy = abs_i16(y1 - y0);
	int16_t sx = (x0 < x1) ? 1 : -1;
	int16_t sy = (y0 < y1) ? 1 : -1;
	int16_t err = dx - dy;
	int16_t e2;

	for (;;) {
		if (x0 >= 0 && x0 < (int16_t)gfx_width && y0 >= 0 && y0 < (int16_t)gfx_height) {
			volatile uint8_t* pixel = gfx_buffer + y0 * gfx_pitch + x0 * gfx_bpp;
			pixel[0] = b;
			pixel[1] = g;
			pixel[2] = r;
			if (gfx_bpp == 4) pixel[3] = 0xFF;
		}
		
		if (x0 == x1 && y0 == y1) {
			break;
		}
		
		e2 = 2 * err;
		if (e2 > -dy) {
			err -= dy;
			x0 += sx;
		}
		if (e2 < dx) {
			err += dx;
			y0 += sy;
		}
	}
}

/*=============================================================================
 * Public API - Called from Rust kernel
 *===========================================================================*/

void set_framebuffer_address(uint32_t addr, uint32_t pitch)
{
	gfx_buffer = (volatile uint8_t*)(uintptr_t)addr;
	gfx_pitch = pitch;
}

/* bpp_bytes: bytes per pixel (e.g., 4 for 32 bpp GOP). */
void set_framebuffer_info(uint32_t addr, uint32_t pitch, uint32_t width, uint32_t height, uint32_t bpp_bytes)
{
	gfx_buffer = (volatile uint8_t*)(uintptr_t)addr;
	gfx_pitch = pitch;
	gfx_width = width;
	gfx_height = height;
	gfx_bpp = bpp_bytes ? bpp_bytes : VGA_GFX_BPP;
}

uint32_t get_framebuffer_address(void)
{
	return (uint32_t)(uintptr_t)gfx_buffer;
}

uint32_t get_screen_width(void)
{
	return gfx_width;
}

uint32_t get_screen_height(void)
{
	return gfx_height;
}

void initialize_vga_graphics(void)
{
	gfx_initialize();
}

void put_pixel_vga(uint16_t x, uint16_t y, uint32_t color)
{
	gfx_put_pixel(x, y, (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF);
}

void clear_screen_vga(uint32_t color)
{
	gfx_clear_screen((color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF);
}

void draw_rect_vga(uint16_t x, uint16_t y, uint16_t width, uint16_t height, uint32_t color)
{
	gfx_draw_rect(x, y, width, height, (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF);
}

void draw_line_vga(int16_t x0, int16_t y0, int16_t x1, int16_t y1, uint32_t color)
{
	gfx_draw_line(x0, y0, x1, y1, (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF);
}

