/* Text cursor position */
static uint16_t text_cursor_x = 0;
static uint16_t text_cursor_y = 0;
static uint32_t text_fg_color = 0xFFFFFF;  /* White */
static uint32_t text_bg_color = 0x000000;  /* Black */

#define CHAR_WIDTH  8
#define CHAR_HEIGHT 16

static void gfx_draw_char(uint16_t x, uint16_t y, char c)
{
	uint8_t ch = (uint8_t)c;
	if (ch >= 128) ch = '?';
	
	const uint8_t* glyph = font_8x16[ch];
	uint8_t r_fg = (text_fg_color >> 16) & 0xFF;
	uint8_t g_fg = (text_fg_color >> 8) & 0xFF;
	uint8_t b_fg = text_fg_color & 0xFF;
	uint8_t r_bg = (text_bg_color >> 16) & 0xFF;
	uint8_t g_bg = (text_bg_color >> 8) & 0xFF;
	uint8_t b_bg = text_bg_color & 0xFF;
	
	for (uint16_t row = 0; row < CHAR_HEIGHT; row++) {
		uint8_t bits = glyph[row];
		for (uint16_t col = 0; col < CHAR_WIDTH; col++) {
			uint16_t px = x + col;
			uint16_t py = y + row;
			if (px < gfx_width && py < gfx_height) {
				volatile uint8_t* pixel = gfx_buffer + py * gfx_pitch + px * gfx_bpp;
				if (bits & (0x80 >> col)) {
					pixel[0] = b_fg;
					pixel[1] = g_fg;
					pixel[2] = r_fg;
					if (gfx_bpp == 4) pixel[3] = 0xFF;
				} else {
					pixel[0] = b_bg;
					pixel[1] = g_bg;
					pixel[2] = r_bg;
					if (gfx_bpp == 4) pixel[3] = 0xFF;
				}
			}
		}
	}
}

static void gfx_newline(void)
{
	text_cursor_x = 0;
	text_cursor_y += CHAR_HEIGHT;
	
	/* Check for scroll (simple implementation - just wrap) */
	if (text_cursor_y + CHAR_HEIGHT > gfx_height) {
		text_cursor_y = 0;
	}
}

static void gfx_putchar(char c)
{
	if (c == '\n' || c == '\r') {
		gfx_newline();
		return;
	}
	
	if (c == '\0') {
		return;
	}
	
	/* Calculate max chars per line */
	uint16_t max_x = gfx_width / CHAR_WIDTH;
	
	gfx_draw_char(text_cursor_x * CHAR_WIDTH, text_cursor_y, c);
	text_cursor_x++;
	
	if (text_cursor_x >= max_x) {
		gfx_newline();
	}
}

static void gfx_puts(const char* str)
{
	while (*str) {
		gfx_putchar(*str++);
	}
}

