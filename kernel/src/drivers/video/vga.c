/**
 * Write a single pixel to the screen at the specified position with RGB color components.
 * 
 * @param x X coordinate (0 = left edge)
 * @param y Y coordinate (0 = top edge)
 * @param r Red component (0-255)
 * @param g Green component (0-255)
 * @param b Blue component (0-255)
 */
void write_pixel(uint16_t x, uint16_t y, uint8_t r, uint8_t g, uint8_t b)
{
	gfx_put_pixel(x, y, r, g, b);
}

/**
 * Write a single pixel to the screen at the specified position with packed RGB color.
 * 
 * @param x X coordinate (0 = left edge)
 * @param y Y coordinate (0 = top edge)
 * @param color Packed RGB color (0xRRGGBB format)
 */
void write_pixel_rgb(uint16_t x, uint16_t y, uint32_t color)
{
	put_pixel_vga(x, y, color);
}

/**
 * Write a single pixel using a pixel structure.
 */
typedef struct {
	uint16_t x;
	uint16_t y;
	uint8_t r;
	uint8_t g;
	uint8_t b;
} pixel_t;

void write_pixel_struct(const pixel_t* pixel)
{
	if (pixel != (void*)0) {
		gfx_put_pixel(pixel->x, pixel->y, pixel->r, pixel->g, pixel->b);
	}
}

/**
 * Read a pixel color from the screen at the specified position.
 * 
 * @param x X coordinate
 * @param y Y coordinate
 * @return Packed RGB color (0xRRGGBB format), or 0 if out of bounds
 */
uint32_t read_pixel(uint16_t x, uint16_t y)
{
	if (x < gfx_width && y < gfx_height) {
		volatile uint8_t* pixel = gfx_buffer + y * gfx_pitch + x * gfx_bpp;
		return ((uint32_t)pixel[2] << 16) | ((uint32_t)pixel[1] << 8) | pixel[0];
	}
	return 0;
}

/**
 * Check if a coordinate is within screen bounds.
 * 
 * @param x X coordinate
 * @param y Y coordinate
 * @return 1 if valid, 0 if out of bounds
 */
int is_valid_pixel_position(uint16_t x, uint16_t y)
{
	return (x < gfx_width && y < gfx_height) ? 1 : 0;
}

/**
 * Write multiple pixels to the screen from an array of pixel structures.
 * 
 * @param pixels Array of pixel_t structures containing position and color info
 * @param count Number of pixels in the array
 */
void write_pixels(const pixel_t* pixels, uint32_t count)
{
	if (pixels == (void*)0) {
		return;
	}
	
	for (uint32_t i = 0; i < count; i++) {
		if (pixels[i].x < gfx_width && pixels[i].y < gfx_height) {
			volatile uint8_t* pixel = gfx_buffer + pixels[i].y * gfx_pitch + pixels[i].x * gfx_bpp;
			pixel[0] = pixels[i].b;
			pixel[1] = pixels[i].g;
			pixel[2] = pixels[i].r;
			if (gfx_bpp == 4) pixel[3] = 0xFF;
		}
	}
}

/**
 * Pixel with packed RGB color for batch operations.
 */
typedef struct {
	uint16_t x;
	uint16_t y;
	uint32_t color;  /* 0xRRGGBB format */
} pixel_rgb_t;

/**
 * Write multiple pixels to the screen from an array with packed RGB colors.
 * The array must be terminated with a pixel where x == 0xFFFF (sentinel value).
 * 
 * @param pixels Array of pixel_rgb_t structures containing position and packed color
 */
void write_pixels_rgb(const pixel_rgb_t* pixels)
{
	if (pixels == (void*)0) {
		return;
	}
	
	for (uint32_t i = 0; pixels[i].x != 0xFFFF; i++) {
		if (pixels[i].x < gfx_width && pixels[i].y < gfx_height) {
			volatile uint8_t* pixel = gfx_buffer + pixels[i].y * gfx_pitch + pixels[i].x * gfx_bpp;
			pixel[0] = pixels[i].color & 0xFF;
			pixel[1] = (pixels[i].color >> 8) & 0xFF;
			pixel[2] = (pixels[i].color >> 16) & 0xFF;
			if (gfx_bpp == 4) pixel[3] = 0xFF;
		}
	}
}

/**
 * Write multiple pixels with separate position and color arrays.
 * Arrays must be terminated with a sentinel value of 0xFFFF for x_coords.
 * 
 * @param x_coords Array of X coordinates (terminated with 0xFFFF)
 * @param y_coords Array of Y coordinates
 * @param colors Array of packed RGB colors (0xRRGGBB format)
 */
void write_pixels_arrays(const uint16_t* x_coords, const uint16_t* y_coords,
						 const uint32_t* colors)
{
	if (x_coords == (void*)0 || y_coords == (void*)0 || colors == (void*)0) {
		return;
	}
	
	for (uint32_t i = 0; x_coords[i] != 0xFFFF; i++) {
		uint16_t x = x_coords[i];
		uint16_t y = y_coords[i];
		if (x < gfx_width && y < gfx_height) {
			volatile uint8_t* pixel = gfx_buffer + y * gfx_pitch + x * gfx_bpp;
			pixel[0] = colors[i] & 0xFF;
			pixel[1] = (colors[i] >> 8) & 0xFF;
			pixel[2] = (colors[i] >> 16) & 0xFF;
			if (gfx_bpp == 4) pixel[3] = 0xFF;
		}
	}
}
